function darken(hex: string, factor = 0.5): string {
  const h = hex.replace('#', '')
  const r = parseInt(h.slice(0, 2), 16)
  const g = parseInt(h.slice(2, 4), 16)
  const b = parseInt(h.slice(4, 6), 16)
  return `rgb(${Math.round(r * (1 - factor))},${Math.round(g * (1 - factor))},${Math.round(b * (1 - factor))})`
}

export default function PixelLandmark({ type, color }: Props) {
  const pattern = PATTERNS[type % PATTERNS.length]
  const shadow = darken(color, 0.5)
  const px = 3

  return (
    <svg
      viewBox={`0 0 ${16 * px} ${16 * px}`}
      width="100%"
      height="100%"
      style={{ imageRendering: 'pixelated', filter: `drop-shadow(${px / 2}px ${px}px 0 ${shadow})` }}
    >
      {pattern.map((row, ri) =>
        row.split('').map((cell, ci) => {
          if (cell === '0') return null
          return (
            <rect
              key={`${ri}-${ci}`}
              x={ci * px}
              y={ri * px}
              width={px}
              height={px}
              fill={cell === '2' ? shadow : color}
            />
          )
        })
      )}
    </svg>
  )
}
